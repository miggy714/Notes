def atomic_form_factor(element, ind_var):
    coeff = atomic_scattering_coeffs[element]
    s = ind_var
    a = coeff["a"]
    b = coeff["b"]
    c = coeff["c"]
    return np.sum(a[:, None] * np.exp(-b[:, None] * s**2), axis=0) + c



 
